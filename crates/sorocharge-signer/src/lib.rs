//! The shared signing engine behind `sorocharge-x402` and `sorocharge-mpp`.
//!
//! This crate builds, signs, and verifies a `SorobanAuthorizationEntry` for
//! exactly one operation — a SEP-41 `transfer(from, to, amount)` — across
//! every credential shape CAP-71 defines (legacy `Address`, `AddressV2`, and
//! delegated signers). It knows nothing about x402 or MPP's wire formats;
//! the two protocol crates translate their own JSON shapes to and from the
//! types here. It also does not talk to Stellar RPC itself: callers submit
//! and poll for settlement through whichever RPC client their protocol
//! adapter uses.
//!
//! Every function that produces XDR is diffed byte-for-byte against a
//! fixture generated by the pinned `@stellar/stellar-sdk` (see
//! `tests/golden_vectors/` at the repo root) — this is the proof that the
//! entries this crate builds are the same bytes the reference SDK would
//! produce for the same inputs, not merely "look right."

#![deny(unsafe_code)]

mod effects;
mod entry;
mod error;
mod sign;
mod verify;

/// The network passphrase for mainnet — shared by the signing engine and
/// protocol adapters when they translate Stellar passphrases into CAIP-2
/// identifiers.
pub const PUBNET_PASSPHRASE: &str = "Public Global Stellar Network ; September 2015";
/// The network passphrase for testnet — shared by the signing engine and
/// protocol adapters when they translate Stellar passphrases into CAIP-2
/// identifiers.
pub const TESTNET_PASSPHRASE: &str = "Test SDF Network ; September 2015";

/// Maps a Stellar network passphrase to the CAIP-2 identifier the protocol
/// adapters expect in their HTTP challenge payloads.
pub fn caip2_for_passphrase(network_passphrase: &str) -> Result<&'static str, SorochargeError> {
    match network_passphrase {
        PUBNET_PASSPHRASE => Ok("stellar:pubnet"),
        TESTNET_PASSPHRASE => Ok("stellar:testnet"),
        other => Err(SorochargeError::UnsupportedNetwork {
            network: other.to_string(),
        }),
    }
}

